import { describe, expect, test } from "vitest";
import tabRows from "../../tab-rows.json";
import type { RowMap } from "./tabMapping.ts";
import {
  FLOW_KEYS,
  FLOW_STAGES,
  GRAPH_KEYS,
  GRAPH_KINDS,
  GRAPH_ROLES,
  SOURCING_ROLES,
  SUPPLIERS_KEYS,
  SUPPLIERS_KINDS,
  TIMELINE_KEYS,
  TIMELINE_KINDS,
} from "./tabMapping.ts";
import { recordedRows, rulesUnreadable, type RecordedTab } from "../fixtures/scenario.ts";

// The frontend half of the tab row vocabulary: every key the mappers read, every enum value
// they understand, and every fixture row's keys and enum values must be in the snapshot the
// backend exports (`tab-rows.json`, regenerated by `just frontend-contracts`). A failure
// names the tab, the fixture and the key.

type Vocabulary = { keys: ReadonlyArray<string>; enums: Readonly<Record<string, ReadonlyArray<string>>> };
const VOCABULARY: Readonly<Record<RecordedTab, Vocabulary>> = tabRows;

const TABS: ReadonlyArray<RecordedTab> = ["timeline", "graph", "flow", "suppliers"];

/** The mapper's declared read keys and enum literals, per tab. */
const MAPPING: Readonly<Record<RecordedTab, { keys: ReadonlyArray<string>; enums: Readonly<Record<string, ReadonlyArray<string>>> }>> = {
  timeline: { keys: TIMELINE_KEYS, enums: { kind: TIMELINE_KINDS } },
  graph: { keys: GRAPH_KEYS, enums: { kind: GRAPH_KINDS, role: GRAPH_ROLES } },
  flow: { keys: FLOW_KEYS, enums: { stage: FLOW_STAGES, sourcing: SOURCING_ROLES } },
  suppliers: { keys: SUPPLIERS_KEYS, enums: { kind: SUPPLIERS_KINDS, sourcing: SOURCING_ROLES } },
};

/** Every problem with `rows` against `tab`'s vocabulary, each naming tab / fixture / key. */
function vocabularyProblems(tab: RecordedTab, fixture: string, rows: ReadonlyArray<RowMap>): string[] {
  const vocabulary = VOCABULARY[tab];
  const problems: string[] = [];
  rows.forEach((row, i) => {
    for (const [key, value] of Object.entries(row)) {
      if (!vocabulary.keys.includes(key)) problems.push(`${tab} · ${fixture} row ${i}: key "${key}" is not in tab-rows.json`);
      const allowed = vocabulary.enums[key];
      if (allowed && !allowed.includes(value)) {
        problems.push(`${tab} · ${fixture} row ${i}: ${key}="${value}" is not in tab-rows.json (${allowed.join(" | ")})`);
      }
    }
  });
  return problems;
}

describe("tab row vocabulary (tab-rows.json)", () => {
  test.each(TABS)("the %s mapper reads only served keys and understands only served enum values", (tab) => {
    const vocabulary = VOCABULARY[tab];
    const { keys, enums } = MAPPING[tab];
    const unknownKeys = keys.filter((k) => !vocabulary.keys.includes(k)).map((k) => `${tab} · mapping: key "${k}"`);
    const unknownValues = Object.entries(enums).flatMap(([key, values]) =>
      values.filter((v) => !(vocabulary.enums[key] ?? []).includes(v)).map((v) => `${tab} · mapping: ${key}="${v}"`),
    );
    expect([...unknownKeys, ...unknownValues]).toEqual([]);
  });

  test.each(TABS)("the %s mapper understands every enum value the backend serves", (tab) => {
    const { enums } = MAPPING[tab];
    const missing = Object.entries(VOCABULARY[tab].enums).flatMap(([key, values]) =>
      values.filter((v) => !(enums[key] ?? []).includes(v)).map((v) => `${tab} · mapping misses ${key}="${v}"`),
    );
    expect(missing).toEqual([]);
  });

  test("every recorded fixture row (and its rules-unreadable shape) stays inside the vocabulary", () => {
    const problems = Object.entries(recordedRows).flatMap(([subject, tabs]) =>
      TABS.flatMap((tab) => [
        ...vocabularyProblems(tab, `recorded ${subject}`, tabs[tab]),
        ...vocabularyProblems(tab, `rules-unreadable ${subject}`, rulesUnreadable(tab, tabs[tab])),
      ]),
    );
    expect(problems).toEqual([]);
    // Every tab of every recorded subject serves rows, so the checks above are not vacuous.
    for (const tabs of Object.values(recordedRows)) for (const tab of TABS) expect(tabs[tab].length).toBeGreaterThan(0);
  });

  test("an unknown key or enum value is reported with its tab, fixture and key", () => {
    expect(vocabularyProblems("flow", "probe", [{ entity: "x", stage: "shipped", colour: "red" }])).toEqual([
      'flow · probe row 0: stage="shipped" is not in tab-rows.json (in_production | in_stock | on_order | promised | suppliers)',
      'flow · probe row 0: key "colour" is not in tab-rows.json',
    ]);
  });
});

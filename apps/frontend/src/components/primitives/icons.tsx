// Inline Lucide icons (stroke-width 1.5), so there is no icon dependency.
import type { SVGProps } from "react";

function icon(path: React.ReactNode) {
  return function Icon({ size = 16, ...props }: SVGProps<SVGSVGElement> & { size?: number }) {
    return (
      <svg
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={1.5}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden="true"
        {...props}
      >
        {path}
      </svg>
    );
  };
}

